CREATE TABLE foods (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    brand TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL DEFAULT 'otro'
        CHECK (category IN ('proteina', 'carbo', 'fruta', 'lacteo', 'grasa', 'preparado', 'otro')),
    protein_g DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (protein_g >= 0),
    carbs_g DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (carbs_g >= 0),
    fat_g DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (fat_g >= 0),
    kcal DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (kcal >= 0),
    per_grams DOUBLE PRECISION NOT NULL DEFAULT 100 CHECK (per_grams > 0),
    serving_grams INT NOT NULL DEFAULT 100 CHECK (serving_grams > 0),
    serving_label TEXT NOT NULL DEFAULT '100 g',
    source TEXT NOT NULL DEFAULT 'local'
);
CREATE INDEX foods_name_lower_idx ON foods (LOWER(name));
CREATE INDEX foods_category_idx ON foods (category);

